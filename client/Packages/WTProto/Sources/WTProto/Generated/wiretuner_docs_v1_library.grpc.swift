/// Team libraries (docs/_includes/library/library.adoc, "Team libraries";
/// docs/_includes/collaboration/sharing.adoc, "Data model"): a team document its owner has
/// marked as a library, whose symbols, styles, master pages and colors every document in the
/// team can draw on.  The server does not know what a symbol is: a library's contents are read
/// by opening the library document read-only through SyncService.FetchSnapshot, and *using*
/// something from a library is a client-side copy into the consuming document that records
/// where it came from in document data (`LibrarySource` on the copied node, doc.v1; decisions.adoc
/// D-035: copy on use, no live cross-document references).  `Library.head_seq` is what the
/// "update available" badge compares that provenance's `server_seq` with.  Color libraries add
/// their own service to this file (COLOR-020).

