/// proto/wiretuner/sync/v1/sync.proto
///
/// The sync protocol (docs/spec/sync-protocol.adoc).  The server is a hub: every change goes
/// to it, it assigns a position in the document's log, and every other client with the document
/// open receives it from that log.  One server-streaming Subscribe carries everything the server
/// has to say about a document; everything the client has to say is a unary call (or, for a bulk
/// upload, a client-streaming one with a unary fallback).  No RPC streams in both directions --
/// tools/proto/check-no-bidi.sh enforces it -- so every call works through a Connect or gRPC-Web
/// gateway and an HTTP/1.1 load balancer (docs/spec/api-conventions.adoc, "Services and RPC
/// shape"; docs/spec/decisions.adoc D-044).
///
/// Presence (docs/_includes/collaboration/presence.adoc, "Data model") and the document events
/// a session receives (sharing.adoc, branches.adoc) are here too: they are frames of the one
/// subscription.  This package imports doc.v1 and account.v1 only; docs.v1 imports it for
/// Participant, so nothing here may import docs.v1 (buf's PACKAGE_NO_IMPORT_CYCLE).

