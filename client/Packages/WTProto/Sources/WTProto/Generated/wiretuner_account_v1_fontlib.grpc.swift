/// proto/wiretuner/account/v1/fontlib.proto
///
/// Team font libraries (docs/_includes/document/font-substitution.adoc, "Team font library";
/// TXT-002's server half).  A team's admins upload licensed font files; every member above guest
/// lists the catalog and fetches the files, which WTText activates for the process only when a
/// document names a family the Mac does not have.  A font file is a content-addressed blob (the
/// `blob` table and object storage, as BlobService keeps them) referenced by the team rather than
/// by a document.  Only files whose every face's OpenType `OS/2.fsType` allows document embedding
/// (installable or editable, with outlines) are accepted: the rule WTText's `FontEmbedding`
/// applies before a font is embedded in a document.

