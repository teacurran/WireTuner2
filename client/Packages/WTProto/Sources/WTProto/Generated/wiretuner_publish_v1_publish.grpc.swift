/// proto/wiretuner/publish/v1/publish.proto
///
/// Publishing a document to a web link (docs/_includes/web/publish-html.adoc, "Publishing to a web
/// link"; WEB-011).  The client renders the HTML bundle, uploads every file through
/// wiretuner.blob.v1.BlobService (which associates each blob with the document), and registers
/// the bundle here with a manifest of paths and blob hashes.  The server keeps publishes as rows,
/// never as document content, and serves the current one of each document on a separate origin,
/// `https://pub.<host>/d/<document id>/`, so published pages can never read app state or call the
/// API with a viewer's credentials.
///
/// Errors: an unknown publish, or one on a document the caller cannot see, is NOT_FOUND with
/// reason DOCUMENT_NOT_FOUND; a manifest naming a blob the document does not reference is
/// NOT_FOUND with reason BLOB_NOT_FOUND; a bundle over 512 MiB is INVALID_ARGUMENT with reason
/// VALIDATION_FAILED; more than 30 publishes of one document in an hour is RESOURCE_EXHAUSTED with
/// reason RATE_LIMITED and RetryInfo.

